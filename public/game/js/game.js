function getTubeColorSnapshot(thisTube) {
    var colors = [];
    for (var n = 0; n < thisTube.data.colors.length; n++) {
        colors.push({
            index: thisTube.data.colors[n].index,
            height: thisTube.data.colors[n].height
        });
    }
    return colors;
}

function createGameplaySnapshot() {
    var tubes = [];
    for (var n = 0; n < gameData.tubes.length; n++) {
        tubes.push({
            fill: gameData.tubes[n].data.fill,
            colors: getTubeColorSnapshot(gameData.tubes[n])
        });
    }

    return {
        moveCount: gameplayPolishData.moveCount,
        undoCount: gameplayPolishData.undoCount,
        completedTubes: gameplayPolishData.completedTubes,
        tubes: tubes
    };
}

function stagePendingMoveSnapshot() {
    gameplayPolishData.pendingMove = createGameplaySnapshot();
}

function commitPendingMoveSnapshot() {
    if (gameplayPolishData.pendingMove == null || gameplayPolishData.complete) {
        gameplayPolishData.pendingMove = null;
        return;
    }

    gameplayPolishData.undoStack.push(gameplayPolishData.pendingMove);
    gameplayPolishData.pendingMove = null;
    gameplayPolishData.moveCount++;
    updateCompletedTubeCount();
    recordGameplayRewardMove();
    clearAssistMessage();
    updateGameplayPolishUI();
}

function resetTubeTweenState(thisTube) {
    TweenMax.killTweensOf(thisTube);
    TweenMax.killTweensOf(thisTube.data.mask);
    TweenMax.killTweensOf(thisTube.data.imageBack);
    TweenMax.killTweensOf(thisTube.data.imageFront);
    TweenMax.killTweensOf(thisTube.data.container);
    thisTube.data.mask.rotation = 0;
    thisTube.data.imageBack.rotation = 0;
    thisTube.data.imageFront.rotation = 0;
    thisTube.data.container.y = 0;
    thisTube.data.fillShape.graphics.clear();
    thisTube.data.fillShape.visible = false;
    thisTube.data.active = true;
    thisTube.data.direction = "";
}

function restoreGameplaySnapshot(snapshot) {
    if (snapshot == null) {
        return;
    }

    gameData.pouring = [];
    gameData.filling = false;

    for (var n = 0; n < gameData.tubes.length; n++) {
        var thisTube = gameData.tubes[n];
        var tubeSnapshot = snapshot.tubes[n];
        resetTubeTweenState(thisTube);
        thisTube.data.colors = [];
        thisTube.data.fill = tubeSnapshot.fill;

        // Snapshots store only serializable color data; display objects are rebuilt here.
        for (var c = 0; c < tubeSnapshot.colors.length; c++) {
            thisTube.data.colors.push({
                shape: null,
                surface: null,
                bottom: null,
                symbol: null,
                index: tubeSnapshot.colors[c].index,
                height: tubeSnapshot.colors[c].height
            });
        }

        fillLiquid(n);
        updateTubeData(thisTube);
    }

    positionTubes();
    gameplayPolishData.moveCount = snapshot.moveCount;
    gameplayPolishData.completedTubes = snapshot.completedTubes;
    gameplayPolishData.pendingMove = null;
    breakGameplayFlow();
    gameData.action = true;
    updateGameplayPolishUI();
}

function undoLastMove() {
    if (!canUndoMove()) {
        playSound('soundError');
        return;
    }

    var snapshot = gameplayPolishData.undoStack.pop();
    gameplayPolishData.undoCount++;
    restoreGameplaySnapshot(snapshot);
    playSound('soundButton');
}

function canUndoMove() {
    return curPage == 'game' &&
        !gameData.paused &&
        gameData.action &&
        !gameData.filling &&
        !isPourInProgress() &&
        !gameplayPolishData.complete &&
        gameplayPolishData.undoStack.length > 0;
}

function isPourInProgress() {
    if (!gameData.pouring) {
        return false;
    }
    for (var index = 0; index < gameData.pouring.length; index++) {
        if (gameData.pouring[index].filling) {
            return true;
        }
    }
    return false;
}

function getStageTargetTubeCount() {
    var stageSettings = levelSettings[gameData.levelNum];
    return Math.max(1, stageSettings.tubes - stageSettings.empty);
}

function updateCompletedTubeCount() {
    var completed = 0;
    for (var n = 0; n < gameData.tubes.length; n++) {
        var thisTube = gameData.tubes[n];
        var checkColor = -1;
        var completeColor = thisTube.data.fill >= gameData.tube.fillH - 5 && thisTube.data.fill > 0;

        for (var c = 0; c < thisTube.data.colors.length; c++) {
            if (checkColor == -1) {
                checkColor = thisTube.data.colors[c].index;
            } else if (checkColor != thisTube.data.colors[c].index) {
                completeColor = false;
            }
        }

        if (completeColor) {
            completed++;
        }
    }
    gameplayPolishData.completedTubes = completed;
}

function calculateStageStars() {
    var stageSettings = levelSettings[gameData.levelNum];
    var parMoves = MasteryObjectives.getParMoves(stageSettings);
    var adjustedMoves = gameplayPolishData.moveCount + (gameplayPolishData.undoCount * 2) + (gameplayPolishData.hintCount * 2);

    if (adjustedMoves <= Math.ceil(parMoves * 1.2)) {
        return 3;
    }
    if (adjustedMoves <= Math.ceil(parMoves * 1.8)) {
        return 2;
    }
    return 1;
}

function getStarText(stars) {
    var text = '';
    for (var n = 0; n < 3; n++) {
        text += String.fromCharCode(n < stars ? 9733 : 9734);
    }
    return text;
}

function getResultPolishMessage() {
    if (!gameplayPolishData.complete) {
        return textDisplay.tryAgain;
    }
    if (gameplayPolishData.stars == 3) {
        return textDisplay.perfectSort;
    }
    if (gameplayPolishData.stars == 2) {
        return textDisplay.greatSort;
    }
    return textDisplay.clearedSort;
}

function completeGameplayPolish() {
    gameplayPolishData.complete = true;
    gameplayPolishData.pendingMove = null;
    updateCompletedTubeCount();
    gameplayPolishData.stars = calculateStageStars();
    gameplayPolishData.objectives = getCurrentMasteryObjectives();
    gameplayPolishData.bestResult = recordGameplayBest();
    gameplayPolishData.completionReward = recordGameplayProgression();
    if (gameplayPolishData.completionReward && gameplayPolishData.completionReward.essenceEarned > 0) {
        showGameplayRewardMessage('+' + gameplayPolishData.completionReward.essenceEarned + ' Essence');
    }
    CompletionEffects.playCelebration(gameplayPolishData.stars);
    updateGameplayPolishUI();
}

function getCurrentMasteryObjectives() {
    return MasteryObjectives.evaluate(levelSettings[gameData.levelNum], {
        moves: gameplayPolishData.moveCount,
        undos: gameplayPolishData.undoCount,
        hints: gameplayPolishData.hintCount,
        bestCombo: getGameplayRewardState().bestCombo
    });
}

function recordGameplayProgression() {
    if (gameData.type != 'level' && gameData.type != 'daily' && gameData.type != 'challenge') {
        return null;
    }
    var profileMode = gameData.type == 'daily' ? 'daily' : 'level';
    var identifier = profileMode == 'daily' ? DailyChallenge.getDescriptor().dateKey : gameData.levelNum + 1;
    return PlayerProfile.recordCompletion({
        mode: profileMode,
        identifier: identifier,
        stars: gameplayPolishData.stars,
        moves: gameplayPolishData.moveCount,
        undos: gameplayPolishData.undoCount,
        hints: gameplayPolishData.hintCount,
        bestCombo: getGameplayRewardState().bestCombo,
        objectives: gameplayPolishData.objectives
    });
}

function recordGameplayBest() {
    if (typeof PlayerProgress == 'undefined' || (gameData.type != 'level' && gameData.type != 'daily' && gameData.type != 'challenge')) {
        return null;
    }

    var identifier = gameData.levelNum + 1;
    var progressMode = gameData.type == 'challenge' ? 'level' : gameData.type;
    if (gameData.type == 'daily') {
        identifier = DailyChallenge.getDescriptor().dateKey;
    }

    return PlayerProgress.recordBest({
        mode: progressMode,
        identifier: identifier,
        stars: gameplayPolishData.stars,
        moves: gameplayPolishData.moveCount,
        undos: gameplayPolishData.undoCount,
        hints: gameplayPolishData.hintCount,
        bestCombo: getGameplayRewardState().bestCombo
    });
}

function getGameplayRewardState() {
    if (typeof GameplayRewards == 'undefined') {
        return { combo: 0, bestCombo: 0 };
    }
    return GameplayRewards.getState();
}

function recordGameplayRewardMove() {
    if (typeof GameplayRewards == 'undefined') {
        return;
    }

    var reward = GameplayRewards.recordMove(gameplayPolishData.completedTubes);
    var flowCounter = $('#htmlFlowCounter');
    flowCounter.removeClass('is-pulsing');
    if (flowCounter.length > 0) {
        flowCounter[0].offsetWidth;
    }
    flowCounter.addClass('is-pulsing');

    if (reward.milestone) {
        showGameplayRewardMessage(reward.message);
    }
    if (reward.sealedTubes > 0) {
        CompletionEffects.playTubeSeal();
    }
}

function breakGameplayFlow() {
    if (typeof GameplayRewards != 'undefined') {
        GameplayRewards.breakCombo(gameplayPolishData.completedTubes);
    }
    clearGameplayRewardMessage();
}

function showGameplayRewardMessage(message) {
    window.clearTimeout(gameplayRewardToastTimer);
    $('#htmlRewardText').text(message);
    $('#htmlRewardToast').removeClass('is-hidden');
    gameplayRewardToastTimer = window.setTimeout(clearGameplayRewardMessage, 1500);
}

function clearGameplayRewardMessage() {
    window.clearTimeout(gameplayRewardToastTimer);
    gameplayRewardToastTimer = null;
    $('#htmlRewardToast').addClass('is-hidden');
}

function getCurrentGameplayBest() {
    if (typeof PlayerProgress == 'undefined') {
        return null;
    }
    if (gameData.type == 'level') {
        return PlayerProgress.getLevelBest(gameData.levelNum + 1);
    }
    if (gameData.type == 'challenge') {
        return PlayerProgress.getLevelBest(gameData.levelNum + 1);
    }
    if (gameData.type == 'daily' && typeof DailyChallenge != 'undefined') {
        return PlayerProgress.getDailyBest(DailyChallenge.getDescriptor().dateKey);
    }
    return null;
}

function getGameplayStageDisplay() {
    if (gameData.type == 'daily') {
        return { kind: 'Daily', value: 'Today' };
    }
    if (gameData.type == 'challenge') {
        return { kind: 'Round', value: Math.max(1, gameData.challengeNum || 1) };
    }
    if (gameData.type == 'friend') {
        return { kind: 'Friend', value: gameData.levelNum + 1 };
    }
    return { kind: 'Stage', value: gameData.levelNum + 1 };
}

function renderMasteryObjectives() {
    if ($('#htmlMasteryObjectives').length == 0) {
        return;
    }
    var objectives = gameplayPolishData.complete ? gameplayPolishData.objectives : getCurrentMasteryObjectives();
    var html = '';
    for (var index = 0; index < objectives.length; index++) {
        var objective = objectives[index];
        var complete = gameplayPolishData.complete && objective.complete;
        var onTrack = !gameplayPolishData.complete && objective.complete;
        html += '<li class="game-mastery__item' + (complete ? ' is-complete' : '') + (onTrack ? ' is-on-track' : '') + '">';
        html += '<span class="game-mastery__seal game-mastery__seal--' + objective.id + '" aria-hidden="true"></span>';
        html += '<span><strong>' + objective.title + '</strong><small>' + objective.progress + '</small></span></li>';
    }
    $('#htmlMasteryObjectives').html(html);
}

